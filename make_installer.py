def main():
    ap = argparse.ArgumentParser(description="生成棋盘桌宠安装包")
    ap.add_argument("--src", default=os.path.join(SRC, "dist", "chessboard_desktop_pet"))
    ap.add_argument("--name", default="chessboard_desktop_pet")
    ap.add_argument("--out", default=os.path.join(SRC, "dist"))
    ap.add_argument("--version", default=None, help="默认自动递增")
    ap.add_argument("--iscc", default=None)
    ap.add_argument("--app-dir", default="chessboard_desktop_pet",
                    help="默认安装子目录名(localappdata\\Programs 下)")
    ap.add_argument("--light", action="store_true",
                    help="精简安装包: 源目录须是不带角色包的 make_dist 产物 "
                         "(--roles none --embed-python), 产物名加 _light 后缀, "
                         "同事装完在设置页在线下载角色包; 不动 dist/latest 与全量版本序列")
    args = ap.parse_args()

    if args.light and not args.name.endswith("_light"):
        args.name += "_light"

    src_dir = os.path.abspath(args.src)
    if not os.path.isdir(src_dir):
        sys.exit(f"[X] 源目录不存在: {src_dir}  (先跑 make_dist.py)")
    if os.path.isfile(os.path.join(src_dir, "config.json")):
        print("[i] 源目录里有 config.json: 已被安装器自动排除(Excludes), 不会打进安装包;")
        print("    每个人的昵称/好友/战绩都只存在各自电脑的安装目录里, 互不相干。")
    out_dir = os.path.abspath(args.out)
    os.makedirs(out_dir, exist_ok=True)

    ver = args.version or next_version(out_dir, args.name)
    iscc = find_iscc(args.iscc)

    iss = build_iss(src_dir, args.name, ver, args.app_dir)
    iss_path = os.path.join(SRC, "_tools", f"installer_{args.name}.iss")
    with open(iss_path, "w", encoding="utf-8-sig") as f:
        f.write(iss)

    print(f"[..] 编译安装包 v{ver}  (源: {src_dir})")
    r = subprocess.run([iscc, "/Qp", iss_path], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"[X] ISCC 编译失败:\n{r.stdout[-1500:]}\n{r.stderr[-800:]}")
    setup = os.path.join(out_dir, f"{args.name}_v{ver}_setup.exe")
    if not os.path.isfile(setup):
        sys.exit(f"[X] 编译成功但找不到产物: {setup}\n{r.stdout[-800:]}")
    print(f"[OK] {setup}  {os.path.getsize(setup)/1e6:.0f} MB")
    base = f"{args.name}_v{ver}_setup"
    bin_count = 0
    for extra in sorted(os.listdir(out_dir)):
        if extra.startswith(base + "-") and extra.endswith(".bin"):
            bin_path = os.path.join(out_dir, extra)
            bin_count += 1
            print(f"[OK] {bin_path}  {os.path.getsize(bin_path)/1e6:.0f} MB")
    if args.light:
        if bin_count:
            sys.exit("[X] 精简包不该生成 .bin(检查 DiskSpanning 设置)")
        # 精简包: 不算全量产物, 不进 make_patch 基线/latest, 版本号也不写回源文件夹
        print("[OK] 精简安装包: 发这单个 exe 给同事即可, "
              "角色包由同事装完在设置页在线下载")
        return
    print("[OK] 同事需把 setup.exe 与 setup-*.bin 放在同一文件夹后双击 setup.exe")
    # 同步版本号回源文件夹, 供 make_patch.py 按"最新全量版"定补丁基线
    with open(os.path.join(src_dir, "version.txt"), "w", encoding="utf-8") as f:
        f.write(f"版本: v{ver}\n打包时间: {time.strftime('%Y-%m-%d %H:%M:%S')}\n")
    print(f"[OK] 源文件夹 version.txt 已同步为 v{ver}")
    # 同步 dist/latest/ (整夹发给同事的最新全量版)
    sync_latest(out_dir, args.name)


if __name__ == "__main__":
    main()
