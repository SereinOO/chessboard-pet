"""
把 dist/<name> 文件夹做成真正的安装包(setup.exe): 安装向导 + 桌面快捷方式 + 卸载器

用法:
    python make_installer.py                          # 用 dist/chessboard_desktop_pet 打安装包
    python make_installer.py --src dist/tiny_pet --name tiny_pet   # 测试小包
    python make_installer.py --light                  # 精简安装包(不带角色包, 设置页在线下载)

依赖: Inno Setup 编译器, 默认找 _tools/InnoSetup/ISCC.exe(可用 --iscc 指定)。
产物: dist/<name>_vX.Y.Z_setup.exe + dist/setup-1.bin
    (全量 7GB 超过单 exe 4.2GB 上限, Inno 自动分卷; 两个文件必须放同一文件夹,
     同事双击 setup.exe 即安装。分发时把这两个文件一起拷/发即可)
精简包(--light): 产物只有一个 chessboard_desktop_pet_light_vX.Y.Z_setup.exe
    (约 150MB, 直接发同事), 不生成 .bin、不进 dist/latest、不影响全量版本序列。
"""
import argparse
import os
